import '../i18n/dsh_i18n.dart';

/// 点一下首页那只猫，它说的一句话（用户 2026-10-15 第 4 条要求：
/// 「点击猫咪是不是可以弹出一句话，类似于对话的样子，生动一点」）。
///
/// ## 为什么是**本地写死的几句**，不是"AI 生成"
///
/// 三条理由都很实际：
///   ① 首页点一下就要**立刻**有反应 —— 走模型要联网、要等 1~3 秒，那不叫生动，
///      那叫卡；
///   ② 它说的必须是**不会说错**的话。本地固定文案不会编出"我帮你查到了…"这种
///      根本没有依据的内容；
///   ③ 不发任何网络请求 —— 首页点一下就发一次云端调用，是白烧用户的额度。
///
/// ## 语言（这里有个坑，别踩）
///
/// 每句都必须**写成 `tr('字面量')`**，不能把中文放进一个 List 再 `tr(list[i])`：
/// i18n 检查脚本是按"`tr(` 后面紧跟字符串字面量"来采集 key 的 —— 走变量的话
/// 这些句子不会进翻译表，切到外语会**安静地显示中文**（不报错，很难发现）。
/// 一共有几句（界面/测试用它做边界，别在别处写死数字）。
int get mascotLineCount => 6;

/// 取第 [index] 句（自动回环，负数也能取）。
String mascotLineAt(int index) {
  final n = mascotLineCount;
  final i = ((index % n) + n) % n;
  switch (i) {
    case 0:
      return tr('喵～今天想聊点什么？');
    case 1:
      return tr('点一下「创作台 · 生图」，我给你画一张。');
    case 2:
      return tr('你的会话我都看着呢，一条都没丢。');
    case 3:
      return tr('发消息前记得先把模型选好哦。');
    case 4:
      return tr('写小说、做游戏、剪视频 —— 我都能陪你干。');
    default:
      return tr('别光戳我呀，去发一句话试试嘛。');
  }
}
